MLP_C = r"""#include "ho_mlp.h"

/* Rounding right shift, half away from zero, using shifts of non-negative values only (portable). */
int32_t ho_rshift_round(int64_t v, int s)
{
    const int64_t half = (int64_t)1 << (s - 1);
    if (v >= 0) {
        return (int32_t)((v + half) >> s);
    }
    return (int32_t)(-(((-v) + half) >> s));
}

int ho_mlp_run(const ho_layer_t *layers, uint8_t n_layers, const uint16_t *lut, const int8_t *x, uint16_t *out_q15)
{
    int8_t buf[2][HO_MAX_WIDTH];
    const int8_t *in = x;
    uint8_t cur = 0u;
    uint8_t l;
    for (l = 0u; l < n_layers; ++l) {
        const ho_layer_t *L = &layers[l];
        uint16_t j;
        if (L->n_in > HO_MAX_WIDTH || L->n_out > HO_MAX_WIDTH) {
            return -1;
        }
        for (j = 0u; j < L->n_out; ++j) {
            const int8_t *w = &L->w[(uint32_t)j * L->n_in];
            int32_t acc = L->b[j];
            int32_t y;
            uint16_t i;
            for (i = 0u; i < L->n_in; ++i) {
                acc += (int32_t)w[i] * (int32_t)in[i];
            }
            y = ho_rshift_round((int64_t)acc * (int64_t)L->m[j], HO_Q);
            if (L->act == HO_ACT_RELU) {
                if (y < 0) {
                    y = 0;
                }
                if (y > 127) {
                    y = 127;
                }
                buf[cur][j] = (int8_t)y;
            } else {
                int32_t t = y - HO_LUT_LO;
                int32_t idx;
                int32_t frac;
                int32_t lo;
                int32_t hi;
                if (t < 0) {
                    t = 0;
                }
                if (t > ((HO_LUT_N - 1) << HO_LUT_SHIFT)) {
                    t = (HO_LUT_N - 1) << HO_LUT_SHIFT;
                }
                idx = t >> HO_LUT_SHIFT;
                if (idx > HO_LUT_N - 2) {
                    idx = HO_LUT_N - 2;
                }
                frac = t - (idx << HO_LUT_SHIFT);
                lo = (int32_t)lut[idx];
                hi = (int32_t)lut[idx + 1];
                out_q15[j] = (uint16_t)(lo + (((hi - lo) * frac + (1 << (HO_LUT_SHIFT - 1))) >> HO_LUT_SHIFT));
            }
        }
        if (L->act == HO_ACT_RELU) {
            in = buf[cur];
            cur ^= 1u;
        }
    }
    return 0;
}
"""

PACKET_C = r"""#include "helios_onboard.h"

uint16_t ho_crc16_ccitt(const uint8_t *data, uint32_t n)
{
    uint16_t crc = 0xFFFFu;
    uint32_t i;
    for (i = 0u; i < n; ++i) {
        uint8_t b;
        crc ^= (uint16_t)((uint16_t)data[i] << 8);
        for (b = 0u; b < 8u; ++b) {
            crc = (crc & 0x8000u) ? (uint16_t)((crc << 1) ^ 0x1021u) : (uint16_t)(crc << 1);
        }
    }
    return crc;
}

static void put16(uint8_t *p, uint16_t v) { p[0] = (uint8_t)(v >> 8); p[1] = (uint8_t)v; }
static void put32(uint8_t *p, uint32_t v) { put16(p, (uint16_t)(v >> 16)); put16(p + 2, (uint16_t)v); }

void ho_packet_encode(const ho_alert_t *a, uint8_t out[HO_PACKET_BYTES])
{
    uint16_t crc;
    out[0] = 1u; /* format version */
    out[1] = a->priority;
    out[2] = a->sat_id;
    out[3] = a->flags;
    put32(&out[4], a->unix_time);
    put32(&out[8], (uint32_t)a->lat_e5);
    put32(&out[12], (uint32_t)a->lon_e5);
    put16(&out[16], a->frp_x10);
    put16(&out[18], a->cluster_n);
    out[20] = a->p_esc_u8;
    out[21] = a->p_real_u8;
    crc = ho_crc16_ccitt(out, 22u);
    put16(&out[22], crc);
}
"""


def _model_c(tag: str, qm: Qm.QModel) -> str:
    out = [f"/* {tag.upper()}: {qm.name} — inputs: {', '.join(qm.features)}; outputs: {', '.join(qm.outputs)} */\n"]
    for i, L in enumerate(qm.layers):
        out.append(_arr(f"{tag}_w{i}", "int8_t", L.w))
        out.append(_arr(f"{tag}_b{i}", "int32_t", L.b, 8))
        out.append(_arr(f"{tag}_m{i}", "int32_t", L.m, 8))
    rows = ",\n    ".join(
        f"{{{L.w.shape[1]}u, {L.w.shape[0]}u, {'HO_ACT_RELU' if L.act == 'relu' else 'HO_ACT_SIGMOID'}, {tag}_w{i}, {tag}_b{i}, {tag}_m{i}}}"
        for i, L in enumerate(qm.layers))
    out.append(f"static const ho_layer_t {tag}_layers[{len(qm.layers)}] = {{\n    {rows}\n}};\n")
    # целочисленное масштабирование: x_q = rshift_round((raw_milli - mean_milli) * K, 32), K = 2^32 / (1000 * std * S_IN)
    std = np.where(qm.std > 0, qm.std, 1.0)
    mean_milli = np.round(qm.mean * 1000).astype(np.int64)
    k = np.round((2.0 ** 32) / (1000.0 * std * qm.s_x)).astype(np.int64)
    out.append(_arr(f"{tag}_mean_milli", "int32_t", mean_milli, 8))
    out.append(_arr(f"{tag}_k", "int64_t", k, 6).replace("};", "};").replace("int64_t", "int64_t"))
    out.append("#ifndef HO_NO_FLOAT\n" + _farr(f"{tag}_mean", qm.mean) + _farr(f"{tag}_std", std)
               + _farr(f"{tag}_inv_s", 1.0 / qm.s_x) + "#endif\n")
    return "".join(out)


def _models_c(ai1: Qm.QModel, ai2: Qm.QModel, th: dict) -> str:
    th_q = {k: int(round(float(v) * 32767)) for k, v in th.items()}
    body = ['#include "helios_onboard.h"\n#include "ho_mlp.h"\n\n',
            _arr("ho_sigmoid_lut", "uint16_t", ai1.lut, 12),
            _model_c("ai1", ai1), _model_c("ai2", ai2)]
    body.append(f"""
#define HO_AI1_TH_REAL {th_q['real']}u
#define HO_AI1_TH_HIGH {th_q['high']}u
#define HO_AI1_TH_CRIT {th_q['critical']}u

int ho_ai1_infer(const int8_t x_q[HO_AI1_N_IN], uint16_t out_q15[HO_AI1_N_OUT])
{{
    return ho_mlp_run(ai1_layers, {len(ai1.layers)}u, ho_sigmoid_lut, x_q, out_q15);
}}

int ho_ai2_infer(const int8_t x_q[HO_AI2_N_IN], uint16_t out_q15[HO_AI2_N_OUT])
{{
    return ho_mlp_run(ai2_layers, {len(ai2.layers)}u, ho_sigmoid_lut, x_q, out_q15);
}}

uint8_t ho_ai1_priority(const uint16_t p_q15[HO_AI1_N_OUT])
{{
    if (p_q15[0] < HO_AI1_TH_REAL) {{
        return 0u;
    }}
    if (p_q15[1] >= HO_AI1_TH_CRIT) {{
        return 3u;
    }}
    if (p_q15[1] >= HO_AI1_TH_HIGH) {{
        return 2u;
    }}
    return 1u;
}}

static int8_t clamp_q(int32_t v)
{{
    if (v > 127) {{
        return 127;
    }}
    if (v < -127) {{
        return -127;
    }}
    return (int8_t)v;
}}

void ho_ai1_quantize_milli(const int32_t raw_milli[HO_AI1_N_IN], int8_t x_q[HO_AI1_N_IN])
{{
    uint16_t i;
    for (i = 0u; i < HO_AI1_N_IN; ++i) {{
        x_q[i] = clamp_q(ho_rshift_round(((int64_t)raw_milli[i] - ai1_mean_milli[i]) * ai1_k[i], 32));
    }}
}}

void ho_ai2_quantize_milli(const int32_t raw_milli[HO_AI2_N_IN], int8_t x_q[HO_AI2_N_IN])
{{
    uint16_t i;
    for (i = 0u; i < HO_AI2_N_IN; ++i) {{
        x_q[i] = clamp_q(ho_rshift_round(((int64_t)raw_milli[i] - ai2_mean_milli[i]) * ai2_k[i], 32));
    }}
}}

#ifndef HO_NO_FLOAT
static int8_t quantize_one(float raw, float mean, float std, float inv_s)
{{
    float v = (raw - mean) / std * inv_s;
    v = (v >= 0.0f) ? (v + 0.5f) : (v - 0.5f);
    if (v > 127.0f) {{
        v = 127.0f;
    }}
    if (v < -127.0f) {{
        v = -127.0f;
    }}
    return (int8_t)v;
}}

void ho_ai1_quantize(const float raw[HO_AI1_N_IN], int8_t x_q[HO_AI1_N_IN])
{{
    uint16_t i;
    for (i = 0u; i < HO_AI1_N_IN; ++i) {{
        x_q[i] = quantize_one(raw[i], ai1_mean[i], ai1_std[i], ai1_inv_s[i]);
    }}
}}

void ho_ai2_quantize(const float raw[HO_AI2_N_IN], int8_t x_q[HO_AI2_N_IN])
{{
    uint16_t i;
    for (i = 0u; i < HO_AI2_N_IN; ++i) {{
        x_q[i] = quantize_one(raw[i], ai2_mean[i], ai2_std[i], ai2_inv_s[i]);
    }}
}}
#endif
""")
    return "".join(body)


