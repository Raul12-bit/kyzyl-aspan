# ----------------------------------------------------------------------------- генерация C
def _arr(name: str, ctype: str, values, per_line: int = 16) -> str:
    vals = [str(int(v)) for v in np.asarray(values).ravel()]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def _farr(name: str, values) -> str:
    vals = [f"{float(v):.9g}f" for v in np.asarray(values).ravel()]
    return f"static const float {name}[{len(vals)}] = {{ " + ", ".join(vals) + " };\n"


