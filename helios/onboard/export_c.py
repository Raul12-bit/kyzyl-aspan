def _priority_float(p: np.ndarray, th: dict) -> np.ndarray:
    return np.where(p[:, 0] < th["real"], 0, np.where(p[:, 1] >= th["critical"], 3, np.where(p[:, 1] >= th["high"], 2, 1)))


def _test_vectors(ai1: Qm.QModel, f1: dict, z1: np.ndarray, ai2: Qm.QModel, f2: dict, z2: np.ndarray, th: dict) -> tuple[str, dict]:
    x1, x2 = Qm.quantize_input(z1, ai1.s_x), Qm.quantize_input(z2, ai2.s_x)
    e1, e2 = Qm.int_forward(ai1, x1), Qm.int_forward(ai2, x2)
    pf1, pf2 = Qm.float_forward(f1, z1), Qm.float_forward(f2, z2)
    q1 = np.round(pf1 * 32767).astype(int)
    q2 = np.round(pf2 * 32767).astype(int)
    prio = _priority_float(pf1, th)
    from ..comms import packets

    alert = dict(priority="CRITICAL", stream="VIIRS_NOAA20", unix_time=1794700000, lat=51.12345, lon=71.43210,
                 frp_mw=187.4, cluster_n=12, p_escalation=0.91, p_real=0.987, flags=1)
    pkt = packets.encode(**alert)
    fields = struct.unpack(">BBBBIiiHHBB", pkt[:22])

    def mat(name, ctype, arr):
        rows = ",\n    ".join("{" + ", ".join(str(int(v)) for v in r) + "}" for r in np.asarray(arr))
        return f"static const {ctype} {name}[HO_N_TEST][{np.asarray(arr).shape[1]}] = {{\n    {rows}\n}};\n"

    h = [f"#define HO_N_TEST {len(x1)}\n#include <stdint.h>\n",
         mat("t_ai1_x", "int8_t", x1), mat("t_ai1_exact", "uint16_t", e1), mat("t_ai1_float", "uint16_t", q1),
         f"static const uint8_t t_ai1_prio[HO_N_TEST] = {{{', '.join(str(int(v)) for v in prio)}}};\n",
         mat("t_ai2_x", "int8_t", x2), mat("t_ai2_exact", "uint16_t", e2), mat("t_ai2_float", "uint16_t", q2),
         "static const ho_alert_t t_packet_alert = {"
         f"{fields[1]}u, {fields[2]}u, {fields[3]}u, {fields[4]}u, {fields[5]}, {fields[6]}, {fields[7]}u, {fields[8]}u, {fields[9]}u, {fields[10]}u}};\n",
         f"static const uint8_t t_packet_bytes[24] = {{{', '.join(str(b) for b in pkt)}}};\n"]
    py = {"ai1_max_abs_err": float(np.abs(e1.astype(int) - q1).max() / 32767), "ai2_max_abs_err": float(np.abs(e2.astype(int) - q2).max() / 32767)}
    return "".join(h), py


